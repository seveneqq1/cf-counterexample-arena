(function (global) {
  "use strict";

  var CF = (global.CFArena = global.CFArena || {});

  var RUNTIME_SOURCE = [
    "function cfIsIntToken(tok) {",
    "  return /^-?\\d+$/.test(String(tok));",
    "}",
    "function cfTokenize(input) {",
    "  return String(input).trim().split(/\\s+/).filter(function (x) { return x.length > 0; });",
    "}",
    "function cfOutputsEqual(a, b) {",
    "  var ta = cfTokenize(a == null ? '' : a);",
    "  var tb = cfTokenize(b == null ? '' : b);",
    "  if (ta.length !== tb.length) return false;",
    "  for (var i = 0; i < ta.length; i++) {",
    "    if (ta[i] !== tb[i]) return false;",
    "  }",
    "  return true;",
    "}",
    "function cfCompileNamed(source, name) {",
    "  if (typeof source !== 'string' || !source.length) {",
    "    throw new Error('Missing source for ' + name + '.');",
    "  }",
    "  try {",
    "    return new Function(source + '\\nreturn ' + name + ';')();",
    "  } catch (err) {",
    "    throw new Error('Could not compile ' + name + ': ' + (err && err.message ? err.message : err));",
    "  }",
    "}",
    "function cfStringifyOut(value) {",
    "  if (value === undefined) return '';",
    "  if (typeof value === 'string') return value;",
    "  if (typeof value === 'bigint') return value.toString();",
    "  if (typeof value === 'number' && Number.isFinite(value)) {",
    "    if (Number.isInteger(value)) return String(value);",
    "    return String(value);",
    "  }",
    "  return String(value);",
    "}",
    "function runAttempt(challenge, inputText) {",
    "  if (!challenge) {",
    "    return { status: 'reference_failure', error: 'Missing challenge payload.' };",
    "  }",
    "  if (typeof inputText !== 'string') {",
    "    return { status: 'invalid', validationMessage: 'Input must be text.' };",
    "  }",
    "  var maxChars = challenge.maxInputChars || 8000;",
    "  if (inputText.length > maxChars) {",
    "    return {",
    "      status: 'invalid',",
    "      validationMessage: 'Input exceeds the maximum length of ' + maxChars + ' characters.'",
    "    };",
    "  }",
    "  var parse, validate, sizeOf, buggy, reference, checker;",
    "  try {",
    "    parse = cfCompileNamed(challenge.parseSource, 'parse');",
    "    validate = cfCompileNamed(challenge.validateSource, 'validate');",
    "    sizeOf = cfCompileNamed(challenge.sizeSource, 'sizeOf');",
    "    buggy = cfCompileNamed(challenge.buggySource, 'solve');",
    "    reference = cfCompileNamed(challenge.referenceSource, 'solve');",
    "    if (challenge.checkerSource) checker = cfCompileNamed(challenge.checkerSource, 'check');",
    "  } catch (err) {",
    "    return { status: 'reference_failure', error: String(err && err.message ? err.message : err) };",
    "  }",
    "  if (typeof parse !== 'function' || typeof validate !== 'function' || typeof sizeOf !== 'function' || typeof buggy !== 'function' || typeof reference !== 'function') {",
    "    return { status: 'reference_failure', error: 'A required solver function did not compile.' };",
    "  }",
    "  var parsed;",
    "  try {",
    "    parsed = parse(inputText);",
    "  } catch (err) {",
    "    return { status: 'invalid', validationMessage: String(err && err.message ? err.message : err) };",
    "  }",
    "  var verdict;",
    "  try {",
    "    verdict = validate(parsed, inputText);",
    "  } catch (err) {",
    "    return { status: 'invalid', validationMessage: String(err && err.message ? err.message : err) };",
    "  }",
    "  if (!verdict || verdict.ok === false) {",
    "    return {",
    "      status: 'invalid',",
    "      validationMessage: (verdict && verdict.message) || 'Invalid input.'",
    "    };",
    "  }",
    "  var size;",
    "  try {",
    "    size = sizeOf(parsed);",
    "  } catch (err) {",
    "    return { status: 'reference_failure', error: 'sizeOf failed: ' + (err && err.message ? err.message : err) };",
    "  }",
    "  if (typeof size !== 'number' || !isFinite(size) || size < 0) {",
    "    return { status: 'reference_failure', error: 'sizeOf returned a non-numeric size.' };",
    "  }",
    "  var maxParsed = challenge.maxParsedSize || 400;",
    "  if (size > maxParsed) {",
    "    return {",
    "      status: 'invalid',",
    "      validationMessage: 'Parsed instance size ' + size + ' exceeds the allowed limit ' + maxParsed + '.'",
    "    };",
    "  }",
    "  var buggyOutput = null;",
    "  var referenceOutput = null;",
    "  var buggyErr = null;",
    "  var refErr = null;",
    "  try {",
    "    buggyOutput = cfStringifyOut(buggy(parsed));",
    "  } catch (err) {",
    "    buggyErr = err;",
    "  }",
    "  try {",
    "    referenceOutput = cfStringifyOut(reference(parsed));",
    "  } catch (err) {",
    "    refErr = err;",
    "  }",
    "  if (refErr) {",
    "    return {",
    "      status: 'reference_failure',",
    "      error: String(refErr && refErr.message ? refErr.message : refErr),",
    "      buggyOutput: buggyErr ? null : buggyOutput,",
    "      size: size",
    "    };",
    "  }",
    "  if (buggyErr) {",
    "    return {",
    "      status: 'buggy_crash',",
    "      error: String(buggyErr && buggyErr.message ? buggyErr.message : buggyErr),",
    "      referenceOutput: referenceOutput,",
    "      size: size",
    "    };",
    "  }",
    "  var equal;",
    "  try {",
    "    if (checker) {",
    "      var checked = checker(buggyOutput, referenceOutput, parsed);",
    "      equal = !!(checked && checked.equal);",
    "    } else {",
    "      equal = cfOutputsEqual(buggyOutput, referenceOutput);",
    "    }",
    "  } catch (err) {",
    "    return { status: 'reference_failure', error: 'Checker failed: ' + (err && err.message ? err.message : err) };",
    "  }",
    "  return {",
    "    status: equal ? 'match' : 'hack',",
    "    buggyOutput: buggyOutput,",
    "    referenceOutput: referenceOutput,",
    "    size: size",
    "  };",
    "}"
  ].join("\n");

  var factory = new Function(
    RUNTIME_SOURCE +
      "\nreturn { runAttempt: runAttempt, cfTokenize: cfTokenize, cfOutputsEqual: cfOutputsEqual, cfCompileNamed: cfCompileNamed, cfStringifyOut: cfStringifyOut };"
  );
  var runtime = factory();

  CF.RUNTIME_SOURCE = RUNTIME_SOURCE;
  CF.runAttempt = runtime.runAttempt;
  CF.tokenize = runtime.cfTokenize;
  CF.outputsEqual = runtime.cfOutputsEqual;
  CF.compileNamed = runtime.cfCompileNamed;
  CF.stringifyOut = runtime.cfStringifyOut;

  CF.executionPayload = function (challenge) {
    return {
      id: challenge.id,
      buggySource: challenge.buggySource,
      referenceSource: challenge.referenceSource,
      parseSource: challenge.parseSource,
      validateSource: challenge.validateSource,
      sizeSource: challenge.sizeSource,
      checkerSource: challenge.checkerSource || null,
      maxInputChars: challenge.maxInputChars || 8000,
      maxParsedSize: challenge.maxParsedSize || 400
    };
  };

  CF.WORKER_TAIL = [
    "self.onmessage = function (event) {",
    "  var msg = event.data || {};",
    "  if (msg && msg.type === 'ping') {",
    "    self.postMessage({ type: 'pong' });",
    "    return;",
    "  }",
    "  try {",
    "    var result = runAttempt(msg.challenge, msg.input);",
    "    self.postMessage({ ok: true, result: result });",
    "  } catch (err) {",
    "    self.postMessage({",
    "      ok: false,",
    "      result: {",
    "        status: 'reference_failure',",
    "        error: String(err && err.message ? err.message : err)",
    "      }",
    "    });",
    "  }",
    "};"
  ].join("\n");

  CF.buildWorkerSource = function () {
    return CF.RUNTIME_SOURCE + "\n" + CF.WORKER_TAIL;
  };
})(typeof window !== "undefined" ? window : globalThis);
